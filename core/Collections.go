// matches checks if element satisfies all conditions
func (qb *QueryBuilder[PrimaryKeyT, StructT]) matches(elem *StructT) bool {
	// Check custom filter functions
	for _, fn := range qb.conditions {
		if !fn(elem) {
			return false
		}
	}

	return true
}

// matchCondition checks a single field condition
func (qb *QueryBuilder[PrimaryKeyT, StructT]) matchCondition(
	elem *StructT, cond filterCondition) bool {

	// Get field value using reflection
	v := reflect.ValueOf(elem)
	if v.Kind() == reflect.Ptr {
		v = v.Elem()
	}

	field, ok := qb.collection.cachedAttribute[cond.field]
	if !ok {
		return false
	}

	fieldValue := v.FieldByIndex(field.Index).Interface()

	// Compare based on operator
	switch cond.operator {
	case "=", "==":
		return reflect.DeepEqual(fieldValue, cond.value)
	case "!=":
		return !reflect.DeepEqual(fieldValue, cond.value)
	case ">":
		return compare(fieldValue, cond.value) > 0
	case "<":
		return compare(fieldValue, cond.value) < 0
	case ">=":
		return compare(fieldValue, cond.value) >= 0
	case "<=":
		return compare(fieldValue, cond.value) <= 0
	case "contains":
		return contains(fieldValue, cond.value)
	default:
		return false
	}
}

// compare for numeric/string comparison
func compare(a, b interface{}) int {
	// Handle different types
	switch v := a.(type) {
	case int:
		if bVal, ok := b.(int); ok {
			if v < bVal {
				return -1
			}
			if v > bVal {
				return 1
			}
			return 0
		}
	case string:
		if bVal, ok := b.(string); ok {
			if v < bVal {
				return -1
			}
			if v > bVal {
				return 1
			}
			return 0
		}
	case float64:
		if bVal, ok := b.(float64); ok {
			if v < bVal {
				return -1
			}
			if v > bVal {
				return 1
			}
			return 0
		}
		// Add more types as needed
	}
	return 0
}

// contains for string contains check
func contains(haystack, needle interface{}) bool {
	h, ok1 := haystack.(string)
	n, ok2 := needle.(string)
	if ok1 && ok2 {
		return strings.Contains(h, n)
	}
	return false
}

// sort results by field
func (qb *QueryBuilder[PrimaryKeyT, StructT]) sort(results []*StructT) {
	field, ok := qb.collection.cachedAttribute[qb.orderBy]
	if !ok {
		return
	}

	sort.Slice(results, func(i, j int) bool {
		vi := reflect.ValueOf(results[i]).Elem().FieldByIndex(field.Index).Interface()
		vj := reflect.ValueOf(results[j]).Elem().FieldByIndex(field.Index).Interface()

		cmp := compare(vi, vj)
		if qb.orderDirection == "desc" {
			return cmp > 0
		}
		return cmp < 0
	})
}

