// SaveAsJson will save the snapshot as JSON with the given file path.
// The JSON file will contain the timestamp, name, counter and the data in the snapshot.
func (s *SnapShot[PrimaryKeyT, StructT]) SaveAsJson(filePath string) error {
	data, err := json.Marshal(s)
	if err != nil {
		return err
	}

	return os.WriteFile(filePath, data, 0644)
}

func (s *SnapShot[PrimaryKeyT, StructT]) LoadFromJson(filePath string) error {

	// Read the JSON file
	fileData, err := os.ReadFile(filePath)
	if err != nil {
		return err
	}

	err = json.Unmarshal(fileData, &s)
	if err != nil {
		return err
	}

	return nil
}

// helper function to provide deep copy

// deepCopyValue performs a deep copy of a reflect.Value
func deepCopyValue(src reflect.Value) reflect.Value {
	switch src.Kind() {
	case reflect.Slice:
		if src.IsNil() {
			return src
		}
		// Create a new slice with same length and capacity
		dst := reflect.MakeSlice(src.Type(), src.Len(), src.Cap())
		// Deep copy each element
		for i := 0; i < src.Len(); i++ {
			dst.Index(i).Set(deepCopyValue(src.Index(i)))
		}
		return dst

	case reflect.Map:
		if src.IsNil() {
			return src
		}
		// Create a new map
		dst := reflect.MakeMap(src.Type())
		// Deep copy each key-value pair
		for _, key := range src.MapKeys() {
			dst.SetMapIndex(key, deepCopyValue(src.MapIndex(key)))
		}
		return dst

	case reflect.Ptr:
		if src.IsNil() {
			return src
		}
		// Create a new pointer and deep copy the value it points to
		dst := reflect.New(src.Type().Elem())
		dst.Elem().Set(deepCopyValue(src.Elem()))
		return dst

	case reflect.Struct:
		// Create a new struct and deep copy all fields
		dst := reflect.New(src.Type()).Elem()
		for i := 0; i < src.NumField(); i++ {
			if dst.Field(i).CanSet() {
				dst.Field(i).Set(deepCopyValue(src.Field(i)))
			}
		}
		return dst

	case reflect.Array:
		// Create a new array and deep copy all elements
		dst := reflect.New(src.Type()).Elem()
		for i := 0; i < src.Len(); i++ {
			dst.Index(i).Set(deepCopyValue(src.Index(i)))
		}
		return dst

	default:
		// For primitive types (int, string, bool, float, etc.), just return the value
		return src
	}
}
